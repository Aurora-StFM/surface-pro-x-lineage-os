#!/usr/bin/env bash
# Stage the Surface Pro X firmware for Android's /vendor/firmware
# (prebuilt/firmware/, which device.mk copies into the vendor image).
#
#   build-firmware.sh                  use the linux-surface aarch64-firmware repo
#                                      at the commit the Fedora port pins
#   build-firmware.sh --from-dir DIR   use a tree made by aarch64-firmware's
#                                      scripts/getfw.py from your own Windows
#
# The layout is the same as under /lib/firmware on Fedora, so the paths in the
# device tree (qcom/msft/surface/pro-x-sq2/...) work unchanged. Android has no
# linux-firmware package, so the files Fedora puts in firmware/updates go to
# the top level here.
set -euo pipefail
. "$(dirname "$0")/../lib/common.sh"

require_cmds git

FROM_DIR=""
while [ $# -gt 0 ]; do
    case "$1" in
        --from-dir) FROM_DIR="$(realpath "$2")"; shift 2 ;;
        -h|--help) sed -n '2,13p' "$0"; exit 0 ;;
        *) die "unknown argument: $1" ;;
    esac
done

mkdir -p "$WORK_DIR"

if [ -n "$FROM_DIR" ]; then
    SRC="$FROM_DIR"
    FW_SOURCE="getfw.py output from $FROM_DIR"
else
    load_fedora_kit
    REPO="$WORK_DIR/aarch64-firmware"
    msg "Fetching firmware repository ($FIRMWARE_REPO @ ${FIRMWARE_COMMIT:0:12})"
    git_fetch_commit "$FIRMWARE_REPO" "$REPO" "$FIRMWARE_COMMIT"
    SRC="$REPO/firmware"
    FW_SOURCE="$FIRMWARE_REPO @ $FIRMWARE_COMMIT"
fi

PLAT="qcom/msft/surface/pro-x-sq2"
for f in "$PLAT/qcmpss8180.mbn" "$PLAT/wlanmdsp.mbn" "$PLAT/qcdxkmsuc8180.mbn" \
         "$PLAT/qcadsp8180.mbn" "$PLAT/qccdsp8180.mbn" \
         ath10k/WCN3990/hw1.0/board-2.bin ath10k/WCN3990/hw1.0/firmware-5.bin \
         qcom/a680_sqe.fw qcom/a680_gmu.bin qca/crbtfw21.tlv; do
    [ -e "$SRC/$f" ] || die "firmware file missing: $SRC/$f"
done

msg "Staging firmware ($FW_SOURCE)"
OUT="$PREBUILT_DIR/firmware"
rm -rf "$OUT.new"
mkdir -p "$OUT.new/qcom/msft/surface" "$OUT.new/ath10k/WCN3990/hw1.0" "$OUT.new/qca"

# cp -L: the vendor image is built with PRODUCT_COPY_FILES, which wants files.
cp -RL "$SRC/$PLAT" "$OUT.new/qcom/msft/surface/"
cp -L "$SRC"/ath10k/WCN3990/hw1.0/{board-2.bin,firmware-5.bin} "$OUT.new/ath10k/WCN3990/hw1.0/"
cp -L "$SRC"/qcom/a680_sqe.fw "$SRC"/qcom/a680_gmu.bin "$OUT.new/qcom/"
[ -d "$SRC/qcom/venus-5.2" ] && cp -RL "$SRC/qcom/venus-5.2" "$OUT.new/qcom/"
# Bluetooth: WCN3991 data, plus copies under the crbtfw01/crnv01 names the
# chip asks for because it misreports its ID (same as the Fedora port).
cp -L "$SRC"/qca/crbtfw21.tlv "$SRC"/qca/crnv21.* "$OUT.new/qca/"
cp "$OUT.new/qca/crbtfw21.tlv" "$OUT.new/qca/crbtfw01.tlv"
for f in "$OUT.new"/qca/crnv21.*; do
    cp "$f" "$OUT.new/qca/crnv01.${f##*/crnv21.}"
done

rm -rf "$OUT"
mv "$OUT.new" "$OUT"
echo "Generated by firmware/build-firmware.sh from $FW_SOURCE; do not commit." > "$OUT/README"
msg "Done: $OUT ($(find "$OUT" -type f | wc -l) files)"
